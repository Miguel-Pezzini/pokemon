func seeMap(mat [][]int) {
	numRows := len(mat)
	numCols := len(mat[0])

	for i := 0; i < numRows; i++ {
		for j := 0; j < numCols; j++ {
			switch mat[i][j] {
			case 0:
				fmt.Print(tileFloor)
			case 1:
				fmt.Print(tileWall)
			case 2:
				fmt.Print(tilePlayer)
			case 3:
				fmt.Print(tileDoor)
			case 4:
				fmt.Print(tileBuilding)
			case 5:
				fmt.Print(tileLabDoor)
			case 6:
				fmt.Print(tileNPC)
			case 7:
				fmt.Print(tileBush)
			}
		}
		fmt.Println()
	}
}
