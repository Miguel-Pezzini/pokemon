func fillMatrix(mat [][]int, mapData [][]int, x, y int) {
	numRows := len(mapData)
	numCols := len(mapData[0])

	if len(mat) != numRows || len(mat[0]) != numCols {
		fmt.Println("Erro: A matriz fornecida não tem o tamanho correto.")
		return
	}

	for i := 0; i < numRows; i++ {
		for j := 0; j < numCols; j++ {
			mat[i][j] = mapData[i][j]
		}
	}

	if x >= 0 && x < numRows && y >= 0 && y < numCols {
		mat[x][y] = 2
	} else {
		fmt.Println("Erro: A posição inicial da casa está fora dos limites da matriz.")
	}
}

